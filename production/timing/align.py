#!/usr/bin/env python3
"""Align every shot and graphic cue in script/shots.json to the avatar audio.

Reads the word-level transcripts in timing/ (ElevenLabs Scribe output) and writes
timing/timeline.json with global times (seconds on the final edit, where clip2 is
appended directly after clip1's last video frame).
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent          # production/
REPO = ROOT.parent


def norm(tok: str) -> str:
    return re.sub(r"[^a-z0-9]", "", tok.lower())


def tokens(phrase: str):
    return [t for t in (norm(p) for p in phrase.split()) if t]


def find(words, phrase, start_idx=0):
    want = tokens(phrase)
    toks = [norm(w["w"]) for w in words]
    for i in range(start_idx, len(toks) - len(want) + 1):
        if toks[i:i + len(want)] == want:
            return i
    return None


def frame_count(path: Path) -> int:
    out = subprocess.check_output([
        "ffprobe", "-v", "error", "-select_streams", "v:0", "-count_packets",
        "-show_entries", "stream=nb_read_packets", "-of", "csv=p=0", str(path)])
    return int(out.decode().strip().split(",")[0])


def main():
    cfg = json.loads((ROOT / "script/shots.json").read_text())
    fps = cfg["fps"]

    offsets, clip_words, offset = {}, {}, 0.0
    clip_frames = {}
    for clip in cfg["clips"]:
        offsets[clip["id"]] = offset
        clip_words[clip["id"]] = json.loads((ROOT / clip["transcript"]).read_text())["words"]
        n = frame_count(REPO / clip["file"])
        clip_frames[clip["id"]] = n
        offset += n / fps
    speech_end = offset

    shots, shot_idx, errors = {}, {}, []
    cursor = {c: 0 for c in offsets}
    for s in cfg["shots"]:
        words = clip_words[s["clip"]]
        i = find(words, s["anchor"], cursor[s["clip"]])
        if i is None:
            errors.append(f"shot {s['n']}: anchor not found: {s['anchor']!r}")
            continue
        cursor[s["clip"]] = i + 1
        shot_idx[s["n"]] = (s["clip"], i)
        shots[str(s["n"])] = round(offsets[s["clip"]] + words[i]["s"] - s.get("lead", 0.0), 3)

    cues = {}
    for c in cfg["cues"]:
        clip, i0 = shot_idx[c["shot"]]
        words = clip_words[clip]
        i = find(words, c["phrase"], i0)
        if i is None:
            errors.append(f"cue {c['id']}: phrase not found: {c['phrase']!r}")
            continue
        cues[c["id"]] = round(offsets[clip] + words[i]["s"], 3)

    if errors:
        print("\n".join(errors), file=sys.stderr)
        sys.exit(1)

    total_frames = sum(clip_frames.values()) + int(round(cfg["tailSeconds"] * fps))
    last_word = clip_words[cfg["clips"][-1]["id"]][-1]
    out = {
        "fps": fps,
        "clips": [{"id": c["id"], "file": c["file"], "offset": round(offsets[c["id"]], 3),
                   "frames": clip_frames[c["id"]]} for c in cfg["clips"]],
        "speechEnd": round(speech_end, 3),
        "lastWordEnd": round(offsets[cfg["clips"][-1]["id"]] + last_word["e"], 3),
        "totalFrames": total_frames,
        "duration": round(total_frames / fps, 3),
        "shots": shots,
        "cues": cues,
    }
    (ROOT / "timing/timeline.json").write_text(json.dumps(out, indent=1))
    (ROOT / "timing/timeline.js").write_text(
        "// Generated by timing/align.py — do not edit by hand.\nwindow.TIMELINE = " + json.dumps(out) + ";\n")
    print(f"aligned {len(shots)} shots, {len(cues)} cues; duration {out['duration']}s "
          f"({total_frames} frames)")


if __name__ == "__main__":
    main()
